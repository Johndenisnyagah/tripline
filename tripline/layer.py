"""ATT&CK Navigator layer (format 4.5) built from test results, not from tags alone.

One entry per technique a rule is tagged with:
- score: number of rules for the technique;
- comment: the rule ids;
- metadata: each rule's validation status;
- links: each rule's doc note;
- color: from the test results (spec §10). A technique is *failing* if any of its rules fails,
  *validated* if at least one rule is validated, otherwise *synthetic-only*.
Parents of tagged sub-techniques are listed with showSubtechniques so the layer opens with
them expanded. No tactic is set: techniques show in every tactic they belong to.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from tripline.report import RuleResult

REPO_URL = "https://github.com/Johndenisnyagah/tripline"
DOC_URL = REPO_URL + "/blob/main/docs/rules/{rule_id}.md"

COLORS = {
    "validated": "#2e7d32",  # green
    "synthetic-only": "#f9a825",  # amber
    "failing": "#c62828",  # red
}
LEGEND = {
    "validated": "validated: all tests pass, at least one real true positive",
    "synthetic-only": "synthetic-only: all tests pass, every true positive synthetic",
    "failing": "failing: at least one test fails",
}


def _technique_status(statuses: list[str]) -> str:
    if "failing" in statuses:
        return "failing"
    return "validated" if "validated" in statuses else "synthetic-only"


def build_layer(results: list[RuleResult]) -> dict:
    by_technique: dict[str, list[RuleResult]] = {}
    for result in results:
        for technique in result.techniques:
            by_technique.setdefault(technique, []).append(result)

    techniques = []
    for technique_id in sorted(by_technique):
        rules = by_technique[technique_id]
        status = _technique_status([r.status for r in rules])
        techniques.append(
            {
                "techniqueID": technique_id,
                "score": len(rules),
                "color": COLORS[status],
                "comment": ", ".join(r.rule_id for r in rules),
                "enabled": True,
                "metadata": [{"name": "status", "value": status}]
                + [{"name": r.rule_id, "value": r.status} for r in rules],
                "links": [
                    {"label": r.rule_id, "url": DOC_URL.format(rule_id=r.rule_id)} for r in rules
                ],
                "showSubtechniques": any(t.startswith(technique_id + ".") for t in by_technique),
            }
        )
    tagged = set(by_technique)
    for parent in sorted({t.split(".")[0] for t in tagged if "." in t} - tagged):
        techniques.append({"techniqueID": parent, "showSubtechniques": True, "enabled": True})

    max_score = max((len(r) for r in by_technique.values()), default=1)
    return {
        "name": "tripline",
        "versions": {"attack": "20", "navigator": "5.3.2", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": (
            "Techniques covered by tripline's Sigma rules, coloured by test results: "
            "green = validated (all tests pass, at least one real true positive), "
            "amber = synthetic-only, red = failing. Score = number of rules. "
            "Generated by python -m tripline.report."
        ),
        "sorting": 0,
        "layout": {
            "layout": "side",
            "aggregateFunction": "average",
            "showID": True,
            "showName": True,
            "showAggregateScores": False,
            "countUnscored": False,
            "expandedSubtechniques": "annotated",
        },
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#ffffff", "#66b1ff"], "minValue": 0, "maxValue": max_score},
        "legendItems": [{"label": LEGEND[s], "color": COLORS[s]} for s in COLORS],
        "metadata": [{"name": "source", "value": REPO_URL}],
        "links": [{"label": "tripline", "url": REPO_URL}],
        "showTacticRowBackground": False,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
        "selectVisibleTechniques": False,
    }
